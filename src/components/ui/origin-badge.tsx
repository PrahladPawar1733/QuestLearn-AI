import { BadgeCheck, Shapes, Sparkles } from "lucide-react";
import type { ContentOrigin } from "@/lib/types";
import { Badge } from "./badge";

const LABELS: Record<ContentOrigin, { label: string; title: string; tone: "amber" | "cyan" | "primary" }> = {
  demo_prepared: { label: "Prepared demo", title: "Hand-written and checked sample content. Not generated by AI.", tone: "amber" },
  template: {
    label: "Template-generated",
    title: "Built by a deterministic question generator with new numbers and context, then checked by the validator. Not generated by AI.",
    tone: "cyan",
  },
  ai_generated: { label: "AI · validated", title: "Generated by Gemini, then checked by application code before being shown.", tone: "primary" },
};

export function OriginBadge({ origin, className }: { origin: ContentOrigin; className?: string }) {
  const l = LABELS[origin];
  const Icon = origin === "ai_generated" ? Sparkles : origin === "template" ? Shapes : BadgeCheck;
  return (
    <Badge tone={l.tone} title={l.title} className={className}>
      <Icon /> {l.label}
    </Badge>
  );
}
