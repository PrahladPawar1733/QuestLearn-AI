import type { ContentOrigin } from "@/lib/types";
import { Badge } from "./badge";

/** Where content came from, said plainly. The tooltip carries the detail. */
const LABELS: Record<ContentOrigin, { label: string; title: string }> = {
  demo_prepared: { label: "Sample", title: "Hand-written and checked sample content. Not generated by AI." },
  template: {
    label: "Generated from a template",
    title: "Built by a deterministic question generator with new numbers and context, then checked by the validator. Not generated by AI.",
  },
  ai_generated: { label: "AI-written, checked", title: "Generated by Gemini, then checked by application code before being shown." },
};

export function OriginBadge({ origin, className }: { origin: ContentOrigin; className?: string }) {
  const l = LABELS[origin];
  return (
    <Badge title={l.title} className={className}>
      {l.label}
    </Badge>
  );
}
